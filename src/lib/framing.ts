// 采集画面的取景几何（从 CaptureView.vue 抽出：纯布局计算，不含任何采集/录制状态）。
//
// 容器固定尺寸：宽度与页面其余元素对齐（都撑满 max-w-2xl），高度按 4:3 锁定。
// 不用 3:4 —— 满宽下 3:4 会到 896px 高，超出一屏；也不用跟随摄像头宽高比，
// 那会导致每次打开链接布局都不同。video 用 object-cover 填满。
export const BOX_AR = 4 / 3
// 用 BOX_AR 生成，避免与常量各写一份、改一处漏一处。
export const boxStyle = { width: '100%', aspectRatio: `${BOX_AR}` }

// 距离提示只由文案承担（「请靠近镜头」）；这里不再做人脸尺寸到取景洞缩放的映射。
// 原因：原先按「人脸宽 / 画面宽」缩放椭圆（<0.25 缩小、>0.5 放大），
// 该比值在阈值附近抖动时会让椭圆在两种尺寸间反复切换，肉眼看到的就是「镂空框一会儿大一会儿小」。

// 椭圆取景环：高度占容器高 92%，宽度按真人脸型比例反推。
// 原用黄金比 1.618（极为高瘦），在 4:3 满宽容器里宽度只占 38%（约 255px），
// 人脸稍宽就会被遮住下半张脸或两颊。真人脸（含发际线到下巴）高宽比约 1.25~1.4，
// 取 1.3 后椭圆宽约占容器 53%（约 356px），能完整容纳常见人脸。
const OVAL_H = 0.92
const FACE_AR = 1.3

/**
 * 椭圆的位置与尺寸。
 *
 * 【已移除蒙版遮盖】原实现用 box-shadow 的极大 spread（`0 0 0 100vmax #000`）
 * 把椭圆之外涂成纯黑，只留一个椭圆窗口。副作用很严重：椭圆只占容器宽的约 53%，
 * 于是「摄像头取错设备（例如系统默认选中的虚拟摄像头不产帧）」「镜头被挡住」
 * 「画面全黑」「画面停格」这几种情况在界面上**看起来完全一样** ——
 * 都只是一直显示「未检测到人脸」，用户没有任何线索去区分。
 * 现在保留取景环本身（描边 + 发光），环外区域照常显示真实画面。
 */
export function ovalBox() {
  // 椭圆全高（相对容器高）= OVAL_H；换算成相对容器宽的宽度 = OVAL_H × (高/宽) / FACE_AR
  const rxPct = ((OVAL_H * (1 / BOX_AR)) / FACE_AR) * 100
  return {
    width: rxPct + '%',
    height: OVAL_H * 100 + '%',
    // 位置固定、不做任何缩放；只让描边颜色平滑过渡
    transform: 'translate(-50%, -50%)',
    transition: 'box-shadow .2s ease',
  }
}

/**
 * 取景环的描边与发光。**不含涂黑**（见 ovalBox 的说明）。
 * 描边用 spread（无 blur）+ 小半径发光：开销远低于大半径 blur。
 */
export function ovalShadow(ok: boolean): string {
  return ok
    ? '0 0 0 3px #4ade80, 0 0 28px 8px rgba(74,222,128,.65), inset 0 0 24px rgba(74,222,128,.25)'
    : '0 0 0 2px #22d3ee, 0 0 24px 5px rgba(34,211,238,.55), inset 0 0 20px rgba(34,211,238,.18)'
}
